const nl=s=>String(s).split('\n');
function examText(ex,c,ans){
  const o=['أسئلة التربية الإسلامية — '+c.name+' (امتحان تحريري)',''];
  ex.parts.forEach(p=>{
    o.push(p.head+' '+pts(p.pts));
    p.subs.forEach(s=>{
      o.push('',s.title+' '+pts(s.pts)+':');
      const g0=s.groups[0];
      if(g0.lab){o.push('س'+ar(s.qn)+':');
        s.groups.forEach(g=>{o.push('  '+g.lab+') '+g.instr+' '+pts(g.pts));g.items.forEach(x=>{o.push('     '+(x.l?x.l+' ':'')+x.q);if(ans&&x.a)nl(x.a).forEach(z=>o.push('       ← '+z))})})}
      else{o.push('س'+ar(s.qn)+': '+g0.instr);
        g0.items.forEach(x=>{o.push('  '+(x.l?x.l+' ':'')+x.q);if(ans&&x.a)nl(x.a).forEach(z=>o.push('     ← '+z))})}
    });
    o.push('');
  });
  return o.join('\n').trim();
}
function examHtml(ex,esc,ans){
  const row=x=>`<div style="margin-top:4px;padding-inline-start:12px">${x.l?esc(x.l)+' ':''}${esc(x.q)}${ans&&x.a?`<div class="note" style="color:var(--ok)">← ${esc(x.a).replace(/\n/g,'<br>← ')}</div>`:''}</div>`;
  return ex.parts.map(p=>`<div class="item" style="flex-direction:column;align-items:stretch"><b style="font-size:19px">${esc(p.head)} <span class="note">${pts(p.pts)}</span></b>${p.subs.map(s=>{
    const g0=s.groups[0];
    const head=`<div style="margin-top:12px"><b>${esc(s.title)}</b> <span class="note">${pts(s.pts)}</span></div>`;
    if(g0.lab)return head+`<div style="margin-top:4px"><b>س${ar(s.qn)}:</b></div>`+s.groups.map(g=>`<div style="margin-top:4px"><b>${g.lab}) ${esc(g.instr)}</b> <span class="note">${pts(g.pts)}</span></div>`+g.items.map(row).join('')).join('');
    return head+`<div style="margin-top:4px"><b>س${ar(s.qn)}: ${esc(g0.instr)}</b></div>`+g0.items.map(row).join('');
  }).join('')}</div>`).join('');
}
const ETYPES=['امتحانات نصف السنة','امتحانات نهاية السنة','امتحانات شهرية'];
function buildPaper(ex,c,cfg,ans){
  const head={school:cfg.school||'',cls:c.name.replace(/^الصف\s*/,''),subj:SUBJ,time:cfg.time||'',etype:cfg.etype||ETYPES[0],year:cfg.year||'2026/2027'};
  const body=[],P=(t,o)=>body.push(Object.assign({k:'p',t},o||{}));
  const item=(x,ind)=>{nl((x.l?x.l+' ':'')+x.q).forEach(z=>P(z,{ind}));if(ans&&x.a)nl(x.a).forEach(z=>P('الإجابة: '+z,{ind,clr:'1F7A3A',sz:22}))};
  P('اسم الطالب: ..............................................   الشعبة: ..............',{b:1,af:160});
  ex.parts.forEach(p=>{
    P(p.head+' '+pts(p.pts),{b:1,bf:200,af:60,keep:1,sz:28});
    p.subs.forEach(s=>{
      const g0=s.groups[0];
      P(s.title+' '+pts(s.pts)+':',{b:1,bf:120,keep:1});
      if(g0.lab){P('س'+ar(s.qn)+':',{b:1,keep:1});
        s.groups.forEach(g=>{P(g.lab+') '+g.instr+' '+pts(g.pts),{b:1,ind:200,keep:1});g.items.forEach(x=>item(x,500))})}
      else{P('س'+ar(s.qn)+': '+g0.instr,{b:1,keep:1});g0.items.forEach(x=>item(x,300))}
    });
  });
  return {head,body,name:SUBJ+' - '+c.name+' - '+head.etype};
}
